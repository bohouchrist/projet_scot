# Estimation ETP journalière via Hargreaves-Samani, puis conversion en mm par décade
# Utilisée uniquement quand ETP observée est absente.
# C'est une approximation raisonnable pour compléter la base.

def day_of_year_mid_decade(year, month, decade):
    if decade == 1:
        day = 5
    elif decade == 2:
        day = 15
    else:
        last_day = calendar.monthrange(int(year), int(month))[1]
        day = min(25, last_day)
    date = pd.Timestamp(year=int(year), month=int(month), day=int(day))
    return int(date.dayofyear)

def extraterrestrial_radiation_mj(lat_deg, doy):
    # FAO56 - Ra en MJ/m2/jour
    phi = math.radians(lat_deg)
    dr = 1 + 0.033 * math.cos((2 * math.pi / 365) * doy)
    delta = 0.409 * math.sin((2 * math.pi / 365) * doy - 1.39)
    ws = math.acos(max(-1, min(1, -math.tan(phi) * math.tan(delta))))
    gsc = 0.0820  # MJ m-2 min-1
    ra = ((24 * 60) / math.pi) * gsc * dr * (
        ws * math.sin(phi) * math.sin(delta) +
        math.cos(phi) * math.cos(delta) * math.sin(ws)
    )
    return ra

def hargreaves_et0_mm_day(tmin, tmax, tmean, lat_deg, doy):
    # ET0 journalière approximative en mm/jour
    if pd.isna(tmin) or pd.isna(tmax) or pd.isna(tmean) or pd.isna(lat_deg):
        return np.nan
    td = max(tmax - tmin, 0.1)
    ra = extraterrestrial_radiation_mj(lat_deg, doy)
    et0 = 0.0023 * (tmean + 17.8) * math.sqrt(td) * ra
    return max(et0, 0)

