def weighted_mean(x, w):
    x = np.array(x, dtype=float)
    w = np.array(w, dtype=float)
    mask = np.isfinite(x) & np.isfinite(w)
    if mask.sum() == 0:
        return np.nan
    return np.average(x[mask], weights=w[mask])

