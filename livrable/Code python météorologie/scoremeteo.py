# Les scores sont entre 0 et 1.
# Ils traduisent un potentiel agro-climatique général, pas une culture précise.

def trapezoid_score(x, a, b, c, d):
    """
    Score 0..1
    0 avant a
    monte de a à b
    plateau entre b et c
    redescend de c à d
    0 après d
    """
    if pd.isna(x):
        return np.nan
    if x <= a or x >= d:
        return 0.0
    if b <= x <= c:
        return 1.0
    if a < x < b:
        return (x - a) / (b - a)
    if c < x < d:
        return (d - x) / (d - c)
    return 0.0

def descending_penalty(x, good_max, bad_max):
    """
    1 si x <= good_max
    0 si x >= bad_max
    décroissance linéaire entre les deux
    """
    if pd.isna(x):
        return np.nan
    if x <= good_max:
        return 1.0
    if x >= bad_max:
        return 0.0
    return (bad_max - x) / (bad_max - good_max)

def ascending_penalty(x, bad_min, good_min):
    """
    0 si x <= bad_min
    1 si x >= good_min
    croissance linéaire entre les deux
    """
    if pd.isna(x):
        return np.nan
    if x <= bad_min:
        return 0.0
    if x >= good_min:
        return 1.0
    return (x - bad_min) / (good_min - bad_min)

# Sous-scores
# RR favorable 500-800 mm/an
station["S_RR"] = station["RR_ANN_MM"].apply(lambda x: trapezoid_score(x, 300, 500, 800, 1200))

# TM moyenne favorable 15-20°C
station["S_TM"] = station["TM_ANN_C"].apply(lambda x: trapezoid_score(x, 5, 15, 20, 30))

# Tmax favorable <= 30°C, pénalité au-delà, nul vers 38°C
station["S_TX"] = station["TX_MAX_C"].apply(lambda x: descending_penalty(x, 30, 38))

# Tmin favorable >= 0°C, pénalité sous 0, nul vers -5°C
station["S_TN"] = station["TN_MIN_C"].apply(lambda x: ascending_penalty(x, -5, 0))

# ETP moyenne favorable 4-5 mm/jour
station["S_ETP"] = station["ETP_MM_J"].apply(lambda x: trapezoid_score(x, 1.5, 4.0, 5.0, 7.5))

# Score température composite
station["S_TEMP"] = (
    0.60 * station["S_TM"] +
    0.25 * station["S_TX"] +
    0.15 * station["S_TN"]
)

# Score final
station["SCORE_FINAL"] = (
    0.40 * station["S_RR"] +
    0.35 * station["S_TEMP"] +
    0.25 * station["S_ETP"]
) * 100

# Bornage
station["SCORE_FINAL"] = station["SCORE_FINAL"].clip(0, 100).round(1)

# Classes pour QGIS
def score_class(score):
    if pd.isna(score):
        return "NA"
    if score >= 80:
        return "S1 - tres favorable"
    elif score >= 60:
        return "S2 - favorable"
    elif score >= 40:
        return "S3 - moyennement favorable"
    else:
        return "N - peu favorable"

def score_class_num(score):
    if pd.isna(score):
        return 0
    if score >= 80:
        return 4
    elif score >= 60:
        return 3
    elif score >= 40:
        return 2
    else:
        return 1

def color_hex(class_num):
    return {
        4: "#1a9850",  # vert
        3: "#91cf60",  # vert clair
        2: "#fee08b",  # jaune
        1: "#d73027",  # rouge
        0: "#bdbdbd"   # gris
    }.get(class_num, "#bdbdbd")

station["SCORE_CLASSE"] = station["SCORE_FINAL"].apply(score_class)
station["SCORE_CLASS_NUM"] = station["SCORE_FINAL"].apply(score_class_num)
station["COLOR_HEX"] = station["SCORE_CLASS_NUM"].apply(color_hex)
